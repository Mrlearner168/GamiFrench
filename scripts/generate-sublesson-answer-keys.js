#!/usr/bin/env node
/*
 * Generates the server's sub-lesson answer keys from the app's quiz data.
 *
 *   node scripts/generate-sublesson-answer-keys.js
 *
 * The app still renders its quizzes from src/data/quizzes/*.js, but the score
 * that pays stars and XP is graded by the backend from the learner's answers
 * (see Backend/services/sublesson_grading.py). This script copies only what
 * grading needs - question id, type and answer - into
 * Backend/services/sublesson_answer_keys.json.
 *
 * Run it after editing any quiz file. The Jest test
 * src/data/__tests__/sublesson-answer-keys.test.js fails while the JSON is out
 * of date, so a forgotten run is caught before the backend is deployed.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

/*
 * Only these question types are shown by the sub-lesson quiz stage
 * (see quizItems in src/app/(game)/sublesson.jsx); a question without a type
 * is multiple choice. fill-blank questions are filtered out of the quiz, so
 * they never count towards the score.
 */
const GRADED_QUIZ_TYPES = ['multiple-choice', 'true-false', 'sentence-builder', 'listening'];

// Mirrors QUIZ_POINTS in sublesson.jsx and QUESTION_POINTS on the server.
const QUESTION_POINTS = {
  'multiple-choice': 10,
  'true-false': 10,
  'sentence-builder': 20,
  listening: 10,
};

const MODULE_COUNT = 10;

const OUTPUT_PATH = path.resolve(
  __dirname,
  '..',
  '..',
  '..',
  'Backend',
  'services',
  'sublesson_answer_keys.json'
);

/**
 * Build the answer-key document from `{ 'module-N': quizContent }`.
 * Pure, so the Jest sync test can call it on the real imported data.
 */
function buildAnswerKeys(quizByModule) {
  const sublessons = {};

  for (const [moduleKey, quizContent] of Object.entries(quizByModule)) {
    for (const [subLessonId, questions] of Object.entries(quizContent ?? {})) {
      if (sublessons[subLessonId]) {
        throw new Error(
          `Sub-lesson id "${subLessonId}" appears in both ${sublessons[subLessonId].moduleKey} and ${moduleKey}.`
        );
      }

      const graded = (Array.isArray(questions) ? questions : [])
        .filter((question) => !question?.type || GRADED_QUIZ_TYPES.includes(question.type))
        .map((question) => ({
          id: String(question.id),
          type: question.type ?? 'multiple-choice',
          answer: Array.isArray(question.answer)
            ? question.answer.map(String)
            : String(question.answer ?? ''),
        }));

      const seen = new Set();
      for (const question of graded) {
        if (seen.has(question.id)) {
          throw new Error(`Sub-lesson "${subLessonId}" has two questions with id "${question.id}".`);
        }
        seen.add(question.id);
      }

      sublessons[subLessonId] = { moduleKey, questions: graded };
    }
  }

  const sortedSublessons = {};
  for (const key of Object.keys(sublessons).sort()) {
    sortedSublessons[key] = sublessons[key];
  }

  return {
    _generated:
      'Generated by Frontend/GamiFrench/scripts/generate-sublesson-answer-keys.js from src/data/quizzes. Do not edit by hand.',
    questionPoints: QUESTION_POINTS,
    sublessons: sortedSublessons,
  };
}

function serialize(document) {
  return `${JSON.stringify(document, null, 2)}\n`;
}

/*
 * The quiz files are plain ES modules with a single `export const quizContent`
 * and no imports, so they are evaluated directly instead of pulling Babel into
 * a one-off script.
 */
function loadQuizModule(file) {
  const source = fs.readFileSync(file, 'utf8');
  const sandbox = { module: { exports: {} } };
  vm.runInNewContext(
    source.replace(/export\s+const\s+quizContent\s*=/, 'module.exports.quizContent ='),
    sandbox,
    { filename: file }
  );
  if (!sandbox.module.exports.quizContent) {
    throw new Error(`${file} does not export quizContent.`);
  }
  return sandbox.module.exports.quizContent;
}

function loadQuizByModule() {
  const quizByModule = {};
  for (let index = 1; index <= MODULE_COUNT; index += 1) {
    const file = path.resolve(__dirname, '..', 'src', 'data', 'quizzes', `module${index}.js`);
    quizByModule[`module-${index}`] = loadQuizModule(file);
  }
  return quizByModule;
}

if (require.main === module) {
  const document = buildAnswerKeys(loadQuizByModule());
  fs.writeFileSync(OUTPUT_PATH, serialize(document), 'utf8');
  const count = Object.keys(document.sublessons).length;
  console.log(`Wrote ${count} sub-lesson answer keys to ${OUTPUT_PATH}`);
}

module.exports = { GRADED_QUIZ_TYPES, OUTPUT_PATH, QUESTION_POINTS, buildAnswerKeys, serialize };
