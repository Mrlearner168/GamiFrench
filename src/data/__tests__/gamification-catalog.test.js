/*
 * The backend pays missions and challenges from
 * Backend/services/gamification_catalog.json, built here from the app's own
 * catalogs. This test fails whenever the JSON is out of date. Regenerate it with:
 *
 *   UPDATE_GAMIFICATION_CATALOG=1 npx jest gamification-catalog
 *
 * (PowerShell: $env:UPDATE_GAMIFICATION_CATALOG=1; npx jest gamification-catalog)
 */
import fs from 'fs';
import path from 'path';

import {
  dailyChallengeChest,
  dailyChallengeTemplates,
  weeklyChallengeChest,
  weeklyChallengeTemplates,
} from '@/data/challenges/challengeCatalog';
import { MODULE_DAILY_REWARDS } from '@/data/challenges/moduleDailyChallenge';
import { findSubLessonById, lessonCatalog } from '@/data/lessons/catalog';
import {
  getMissionNumber,
  MISSION_PASS_PERCENTAGE,
  missionCatalog,
} from '@/data/lessons/missionCatalog';

const OUTPUT_PATH = path.resolve(
  __dirname, '..', '..', '..', '..', '..', 'Backend', 'services', 'gamification_catalog.json'
);

// Three daily challenges + the daily chest + the spotlight; weekly goal + chest.
const CLAIM_CAPS = { day: 5, week: 2 };

function buildCatalog() {
  const missions = {};
  for (const mission of [...missionCatalog].sort(
    (a, b) => getMissionNumber(a.id) - getMissionNumber(b.id)
  )) {
    missions[String(getMissionNumber(mission.id))] = {
      moduleKey: mission.moduleId,
      coins: mission.rewards.coins,
      objectives: mission.objectives.map((objective) => objective.targetId),
    };
  }

  const challenges = {};
  const add = (id, period, band, rewards) => {
    challenges[id] = { period, band, xp: rewards.xp, coins: rewards.coins };
  };
  dailyChallengeTemplates.forEach((item) => add(item.id, 'day', item.difficulty, item.rewards));
  weeklyChallengeTemplates.forEach((item) => add(item.id, 'week', 'weekly', item.rewards));
  add(dailyChallengeChest.id, 'day', 'chest', dailyChallengeChest.rewards);
  add(weeklyChallengeChest.id, 'week', 'chest', weeklyChallengeChest.rewards);
  add('module-daily', 'day', 'spotlight', MODULE_DAILY_REWARDS);

  const sortedChallenges = {};
  for (const key of Object.keys(challenges).sort()) sortedChallenges[key] = challenges[key];

  return {
    _generated:
      'Generated by Frontend/GamiFrench/src/data/__tests__/gamification-catalog.test.js. Do not edit by hand.',
    missionPassPercentage: MISSION_PASS_PERCENTAGE,
    claimCaps: CLAIM_CAPS,
    missions,
    challenges: sortedChallenges,
  };
}

const serialize = (document) => `${JSON.stringify(document, null, 2)}\n`;

describe('server gamification catalog', () => {
  const expected = serialize(buildCatalog());

  if (process.env.UPDATE_GAMIFICATION_CATALOG) {
    fs.writeFileSync(OUTPUT_PATH, expected, 'utf8');
  }

  it('is up to date with the mission and challenge catalogs', () => {
    const committed = fs.readFileSync(OUTPUT_PATH, 'utf8').replace(/\r\n/g, '\n');
    expect(committed).toBe(expected);
  });
});

describe('mission catalog', () => {
  const activeSubLessons = lessonCatalog.flatMap((module) =>
    (module.lessons ?? []).flatMap((topic) => (topic.subLessons ?? []).map((sub) => sub.id))
  );
  const objectiveTargets = missionCatalog.flatMap((mission) =>
    mission.objectives.map((objective) => objective.targetId)
  );

  it('covers every active sub-lesson exactly once', () => {
    expect([...objectiveTargets].sort()).toEqual([...activeSubLessons].sort());
  });

  it('points every objective at a sub-lesson of its own module', () => {
    for (const mission of missionCatalog) {
      for (const objective of mission.objectives) {
        const found = findSubLessonById(objective.targetId);
        expect(found).toBeTruthy();
        expect(found.module.id).toBe(mission.moduleId);
      }
    }
  });

  it('uses unique mission and objective ids', () => {
    const ids = missionCatalog.map((mission) => mission.id);
    expect(new Set(ids).size).toBe(ids.length);
    const objectiveIds = missionCatalog.flatMap((m) => m.objectives.map((o) => o.id));
    expect(new Set(objectiveIds).size).toBe(objectiveIds.length);
  });
});

describe('challenge rewards', () => {
  it('stay small next to learning (a full day is at most 55 XP)', () => {
    const maxBand = (band) =>
      Math.max(...dailyChallengeTemplates.filter((t) => t.difficulty === band).map((t) => t.rewards.xp));
    const fullDay =
      maxBand('warmup') + maxBand('core') + maxBand('stretch') +
      dailyChallengeChest.rewards.xp + MODULE_DAILY_REWARDS.xp;
    expect(fullDay).toBeLessThanOrEqual(55);
  });
});
